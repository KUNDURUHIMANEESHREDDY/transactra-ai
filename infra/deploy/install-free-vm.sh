#!/usr/bin/env bash
# Transactra free always-on host bootstrap.
#
# Designed for one of the genuinely free, permanently-available always-on VMs: Oracle Cloud
# Always Free (2 AMD VM.Standard.E2.1.Micro, or Arm Ampere A1 with up to 4 OCPU/24 GB RAM),
# or a Google Cloud always-free e2-micro in a supported region.
#
# What this script does and does not do:
#   - installs Docker and Node 22, enables IPv4 forwarding under UFW, creates the service user
#   - clones/refreshes the repository at /opt/transactra on main only
#   - writes a restrictive /etc/transactra/transactra.env unless one already exists
#   - installs and enables the systemd units for all services
#   It never contacts NVIDIA, Tavily, GitHub, Telegram or Meta, never asks for a credential
# value, and is safe to re-run.
#
# Usage:
#   sudo bash infra/deploy/install-free-vm.sh [path-to-env-file]
set -euo pipefail

REPO_URL="${TRANSACTRA_REPO_URL:-https://github.com/KUNDURUHIMANEESHREDDY/transactra.git}"
REPO_REF="${TRANSACTRA_REPO_REF:-main}"
APP_DIR="${TRANSACTRA_APP_DIR:-/opt/transactra}"
ENV_FILE_TARGET="/etc/transactra/transactra.env"
ENV_SOURCE="${1:-}"
SERVICE_USER="transactra"
RUNTIME_MEMORY_LIMIT_MB="${TRANSACTRA_MEMORY_LIMIT_MB:-900}"

log() { printf '[transactra] %s\n' "$1"; }
die() { printf '[transactra] ERROR: %s\n' "$1" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "run with sudo"

log "target host: $(. /etc/os-release && echo "$PRETTY_NAME") / kernel $(uname -r)"
MEMORY_MB=$(( $(awk '/MemTotal/ {print $2}' /proc/meminfo) / 1024 ))
MEMORY_BUDGET_MB=$(( MEMORY_MB - 350 ))
log "total memory: ${MEMORY_MB}MB; node/service budget after the OS: ${MEMORY_BUDGET_MB}MB"
if (( MEMORY_BUDGET_MB < 500 )); then
  log "WARNING: this host has less than 500MB free for services after the OS."
  log "         Run Postgres and the worker on one VM, or move to the Arm A1 free tier."
fi

if ! command -v docker >/dev/null 2>&1; then
  log "installing docker"
  apt-get update -qq
  apt-get install -y -qq ca-certificates curl gnupg lsb-release >/dev/null
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg | gpg --dearmor -o /etc/apt/keyrings/docker.gpg
  chmod a+r /etc/apt/keyrings/docker.gpg
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" > /etc/apt/sources.list.d/docker.list
  apt-get update -qq
  apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin >/dev/null
fi
log "docker: server $(docker version --format '{{.Server.Version}}' 2>/dev/null || echo 'not responding')"

if ! command -v node >/dev/null 2>&1 || [[ "$(node -v)" != v22.* ]]; then
  log "installing node 22"
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash - >/dev/null
  apt-get install -y -qq nodejs >/dev/null
fi
log "node: $(node -v)"
log "pnpm: $(corepack pnpm --version 2>/dev/null || echo 'will be activated on first use')"

log "creating service user"
id "$SERVICE_USER" >/dev/null 2>&1 || useradd --system --create-home --shell /usr/sbin/nologin "$SERVICE_USER"
if ! id -nG "$SERVICE_USER" | grep -qw docker; then
  usermod -aG docker "$SERVICE_USER"
  log "added $SERVICE_USER to the docker group (grants Docker socket access; see README)"
fi

log "syncing repository at $APP_DIR on $REPO_REF"
install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 0755 "$APP_DIR" "$(dirname "$ENV_FILE_TARGET")"
if [[ -d "$APP_DIR/.git" ]]; then
  git -C "$APP_DIR" fetch origin "$REPO_REF" --quiet
  git -C "$APP_DIR" checkout "$REPO_REF" --quiet
  git -C "$APP_DIR" reset --hard "origin/$REPO_REF" --quiet
else
  rm -rf "$APP_DIR"
  git clone --branch "$REPO_REF" --single-branch --depth 1 "$REPO_URL" "$APP_DIR"
fi
chown -R "$SERVICE_USER:$SERVICE_USER" "$APP_DIR"

log "installing dependencies and building"
sudo -u "$SERVICE_USER" env HOME="/home/$SERVICE_USER" bash -lc "cd $APP_DIR && corepack enable pnpm >/dev/null 2>&1; pnpm install --frozen-lockfile --ignore-scripts && pnpm build"

if [[ ! -f "$ENV_FILE_TARGET" ]]; then
  log "generating $ENV_FILE_TARGET with fresh random credentials"
  install -d -m 0750 -o root -g "$SERVICE_USER" /etc/transactra
  {
    echo "# Generated by install-free-vm.sh. Keep this file root-only; never commit it."
    echo "# Replace the placeholder credentials below with real ones; services fail closed"
    echo "# until each is set, so a missing value is never a simulated success."
    echo "NODE_ENV=production"
    echo "HOST=127.0.0.1"
    echo "PORT=8787"
    echo "CONTROL_PLANE_API_TOKEN=$(openssl rand -hex 32)"
    echo "CONTROL_PLANE_APPROVAL_TOKEN=$(openssl rand -hex 32)"
    echo "CONTROL_PLANE_URL=http://127.0.0.1:8787"
    echo "DATABASE_URL=postgres://transactra:REPLACE_ME@127.0.0.1:5432/transactra"
    echo "TRANSACTRA_OWNER_ID=REPLACE_WITH_OWNER_UUID"
    echo "TRANSACTRA_DATABASE_USER=transactra"
    echo "TRANSACTRA_DATABASE_NAME=transactra"
    echo "TRANSACTRA_DATABASE_PASSWORD=$(openssl rand -hex 24)"
    echo "TRANSACTRA_CYCLE_INTERVAL_MS=900000"
    echo "MONTHLY_SPEND_LIMIT_INR=0"
    echo "TAVILY_PAYG_DISABLED_CONFIRMED=false"
    echo "# TELEGRAM_BOT_TOKEN="
    echo "# TELEGRAM_ALLOWED_USER_IDS="
    echo "# NVIDIA_NIM_API_KEY="
    echo "# TAVILY_API_KEY="
  } > "$ENV_FILE_TARGET"
  chown root:"$SERVICE_USER" "$ENV_FILE_TARGET"
  chmod 0640 "$ENV_FILE_TARGET"
else
  log "keeping the existing $ENV_FILE_TARGET"
fi
# An extra env file carries credentials the operator pastes outside the shell (so they never
# appear in shell history), for example a Telegram bot token. It is merged into the target
# without overwriting anything already set.
if [[ -n "$EXTRA_ENV_FILE" ]]; then
  [[ -f "$EXTRA_ENV_FILE" ]] || die "extra env file not found: $EXTRA_ENV_FILE"
  while IFS= read -r line; do
    case "$line" in \#*|"") continue ;; esac
    key="${line%%=*}"
    [[ -n "$key" && "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
    if grep -q "^${key}=" "$ENV_FILE_TARGET"; then
      sed -i "s|^${key}=.*|${line}|" "$ENV_FILE_TARGET"
    else
      printf '%s\n' "$line" >> "$ENV_FILE_TARGET"
    fi
  done < "$EXTRA_ENV_FILE"
  chown root:"$SERVICE_USER" "$ENV_FILE_TARGET"
  chmod 0640 "$ENV_FILE_TARGET"
  log "merged credentials from $EXTRA_ENV_FILE into $ENV_FILE_TARGET"
fi
if [[ -n "$ENV_SOURCE" ]]; then
  [[ -f "$ENV_SOURCE" ]] || die "env file not found: $ENV_SOURCE"
  install -m 0640 -o root -g "$SERVICE_USER" "$ENV_SOURCE" "$ENV_FILE_TARGET"
  log "installed credentials from $ENV_SOURCE"
fi

log "installing systemd units"
install -d -m 0755 /etc/systemd/system
for unit in "$APP_DIR"/infra/systemd/transactra-*.service; do
  install -m 0644 "$unit" /etc/systemd/system/
done
systemctl daemon-reload
systemctl enable transactra-api.service transactra-scheduler.service transactra-telegram.service transactra-worker.service transactra-whatsapp.service >/dev/null

# Restore the durable organization from a dump produced by transfer-database.mjs. This is what
# makes "everything moves to the cloud" true: the owner UUID (bound into every credential),
# the workforce registry, task history, approvals and memory all survive the move.
if [[ -n "$RESTORE_DUMP" ]]; then
  [[ -f "$RESTORE_DUMP" ]] || die "restore dump not found: $RESTORE_DUMP"
  log "restoring durable state from $RESTORE_DUMP"
  sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='${TRANSACTRA_DATABASE_NAME:-transactra}'" | grep -q 1 \
    || sudo -u postgres createdb -O "${TRANSACTRA_DATABASE_USER:-transactra}" "${TRANSACTRA_DATABASE_NAME:-transactra}"
  sudo -u "$SERVICE_USER" env HOME="/home/$SERVICE_USER" \
    PGPASSWORD="$TRANSACTRA_DATABASE_PASSWORD" \
    psql -U "${TRANSACTRA_DATABASE_USER:-transactra}" -d "${TRANSACTRA_DATABASE_NAME:-transactra}" \
    -h 127.0.0.1 -v ON_ERROR_STOP=0 -q < "$RESTORE_DUMP" >/dev/null \
    || die "restore failed; inspect it with: psql -U transactra -d transactra -f $RESTORE_DUMP"
  log "durable state restored from the dump"
fi

log "applying a default-deny firewall that still allows SSH and outbound HTTPS"
if command -v ufw >/dev/null 2>&1; then
  ufw --force reset >/dev/null
  ufw default deny incoming >/dev/null
  ufw default allow outgoing >/dev/null
  ufw allow 22/tcp comment 'ssh' >/dev/null
  ufw --force enable >/dev/null
  log "ufw: $(ufw status | head -1)"
else
  log "ufw not installed; run: apt-get install -y ufw && follow the same rules"
fi

log "creating a swap file for a 1GB host so the worker survives a memory spike"
if ! swapon --show | grep -q swapfile-transactra; then
  fallocate -l 2G /swapfile-transactra 2>/dev/null || dd if=/dev/zero of=/swapfile-transactra bs=1M count=2048 status=none
  chmod 0600 /swapfile-transactra
  mkswap /swapfile-transactra >/dev/null
  swapon /swapfile-transactra
  grep -q 'swapfile-transactra' /etc/fstab || echo '/swapfile-transactra none swap sw 0 0' >> /etc/fstab
  log "2GB swap enabled (shipped kernels allow zram too: zramctl is preferred on Arm)"
fi

log ""
log "next: node infra/deploy/transactra-doctor.mjs --env-file $ENV_FILE_TARGET --strict"
log "then fill in the real credentials and run: systemctl start transactra-api transactra-scheduler transactra-telegram transactra-worker"
log "A Telegram-only deployment needs no public port, no domain and no certificate: long"
log "polling only requires outbound HTTPS, which the default-allow outgoing rule permits."
